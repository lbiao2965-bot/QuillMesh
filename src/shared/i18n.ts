const messages: Record<AppLanguage, Record<TranslationKey, string>> = {
  en,
  'zh-CN': zhCN,
}

export function normalizeLanguage(value: unknown): AppLanguage | null {
  if (value === 'en' || value === 'zh-CN') return value
  return null
}

export function languageFromLocale(locale: string): AppLanguage {
  return locale.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

export function translate(language: AppLanguage, key: TranslationKey): string {
  return messages[language][key]
}
